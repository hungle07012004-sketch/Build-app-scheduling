import { test, expect } from '@playwright/test';

test('AL13: Excel -> MILP -> accept/apply/execution, then parallel 50-job solvers', async ({page}) => {
  const browserErrors:string[]=[];
  page.on('pageerror',e=>browserErrors.push(e.message));
  await page.goto('/');
  await page.locator('input[type=password]').fill('planner-demo');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Production Dashboard'})).toBeVisible();
  await page.getByRole('button',{name:'Jobs',exact:true}).click();
  await page.getByLabel('Upload Input File').setInputFiles('tests/fixtures/TEST_AL13_10.xlsx');
  await expect(page.getByText(/TEST_AL13_10.xlsx/)).toBeVisible();
  await expect(page.locator('tbody tr')).toHaveCount(10);
  await page.getByRole('button',{name:'Scheduling',exact:true}).click();
  await page.locator('thead button').click();
  await page.getByRole('button',{name:'Validate Data'}).click();
  await expect(page.getByRole('heading',{name:'Data Validation Passed'})).toBeVisible();
  await expect(page.getByText('10 jobs · Small Scale')).toBeVisible();
  await page.getByText('Advanced settings',{exact:true}).click();
  await page.getByLabel('milp_time_limit',{exact:true}).fill('5');
  await page.getByRole('button',{name:'Run Optimization'}).click();
  await expect(page.getByRole('heading',{name:'Scheduling Result'})).toBeVisible({timeout:90_000});
  await page.getByRole('button',{name:'Schedule Table',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(100);
  await page.getByRole('button',{name:'Gantt View',exact:true}).click();
  await expect(page.getByTestId('station-label').filter({hasText:'PRE_01'})).toBeVisible();
  await page.screenshot({path:'test-results/gantt-small.png',fullPage:true});
  await page.getByRole('button',{name:'Accept & Save',exact:true}).click();
  await page.getByRole('button',{name:'Accept & Save',exact:true}).last().click();
  await page.getByRole('button',{name:'Apply to Production'}).click();
  await expect(page.getByRole('heading',{name:'Production Execution'})).toBeVisible();
  await page.getByLabel('Status J001',{exact:true}).selectOption('Completed');
  await expect(page.locator('tbody tr').filter({hasText:'J001'}).getByText('Completed',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await expect(page.getByText('1 / 10',{exact:true})).toBeVisible();

  await page.getByRole('button',{name:'Jobs',exact:true}).click();
  await page.getByLabel('Upload Input File').setInputFiles('tests/fixtures/TEST_AL13_50.json');
  await expect(page.getByText(/TEST_AL13_50.json/)).toBeVisible();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('GA population',{exact:true}).fill('6');
  await page.getByLabel('GA generations',{exact:true}).fill('2');
  await page.getByLabel('MLPSO population',{exact:true}).fill('6');
  await page.getByLabel('MLPSO iterations',{exact:true}).fill('2');
  await page.getByRole('button',{name:'Save Changes'}).click();
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.getByRole('button',{name:'Create Schedule'}).click();
  await page.locator('thead button').click();
  await page.getByRole('button',{name:'Validate Data'}).click();
  await expect(page.getByText('50 jobs · Large Scale')).toBeVisible();
  await expect(page.getByText('Runs: Improved GA + MLPSO',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Run Optimization'}).click();
  await expect(page.getByRole('heading',{name:'Scheduling Result'})).toBeVisible({timeout:90_000});
  await page.getByRole('button',{name:'Algorithm Comparison',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(2);
  await expect(page.locator('tbody tr').filter({hasText:'Improved GA'})).toContainText('Feasible');
  await expect(page.locator('tbody tr').filter({hasText:'MLPSO'})).toContainText('Feasible');
  await page.screenshot({path:'test-results/comparison-large.png',fullPage:true});
  await page.getByRole('button',{name:'Schedule Table',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(500);
  expect(browserErrors).toEqual([]);
});
