import { test, expect } from '@playwright/test';

test('AL13: automatic GA -> accept/apply/execution, then automatic MLPSO for 50 jobs', async ({page,request}) => {
  const browserErrors:string[]=[];
  page.on('pageerror',e=>browserErrors.push(e.message));
  async function verifyAutomaticResult(algorithm:string,operationCount:number) {
    const rid=await page.evaluate(()=>sessionStorage.getItem('al13-run'));
    const token=await page.evaluate(()=>sessionStorage.getItem('al13-token'));
    const response=await request.get('/api/schedules/'+rid+'/result',{headers:{Authorization:'Bearer '+token}});
    expect(response.ok()).toBeTruthy();
    const result=await response.json();
    expect(result.status).toBe('completed');
    expect(result.request.algorithms).toEqual([]);
    expect(result.selection_mode).toBe('Automatic');
    expect(result.algorithms.map((a:any)=>a.algorithm)).toEqual([algorithm]);
    expect(result.selected.algorithm).toBe(algorithm);
    expect(result.selected.feasible).toBe(true);
    expect(result.selected.validation_issues).toEqual([]);
    expect(result.selected.operations).toHaveLength(operationCount);
  }
  await page.goto('/');
  await page.locator('input[type=password]').fill('planner-demo');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Production Dashboard'})).toBeVisible();
  if(await page.getByRole('button',{name:'Input Data',exact:true}).getAttribute('aria-expanded')==='false')await page.getByRole('button',{name:'Input Data',exact:true}).click();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Jobs',exact:true}).click();
  await page.getByLabel('Upload Input File').setInputFiles('tests/fixtures/TEST_AL13_10.xlsx');
  await expect(page.getByText(/TEST_AL13_10.xlsx/)).toBeVisible();
  await expect(page.locator('tbody tr')).toHaveCount(10);
  await page.getByRole('button',{name:'Scheduling Studio',exact:true}).click();
  await page.getByRole('checkbox',{name:'Select all filtered jobs'}).check();
  await page.getByRole('button',{name:'Validate Data'}).click();
  await expect(page.getByRole('heading',{name:'Data Validation Passed'})).toBeVisible();
  await expect(page.getByText('10 jobs · Small Scale')).toBeVisible();
  await expect(page.getByRole('radio',{name:'Automatic',exact:true})).toBeChecked();
  await expect(page.getByText('Runs: GA (Improved GA)',{exact:true})).toBeVisible();
  await page.getByText('Advanced settings',{exact:true}).click();
  // Automatic routing uses GA for this legacy fixture, not the old job-count MILP rule.
  await page.getByLabel('ga_population',{exact:true}).fill('6');
  await page.getByLabel('ga_generations',{exact:true}).fill('2');
  await page.getByRole('button',{name:'Run Optimization'}).click();
  await expect(page.getByRole('heading',{name:'Scheduling Result'})).toBeVisible({timeout:90_000});
  await verifyAutomaticResult('Improved GA',100);
  await page.getByRole('button',{name:'Schedule Table',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(50);
  await expect(page.getByTestId('operation-table')).toContainText('100 / 100 operations');
  await page.getByRole('button',{name:'Gantt View',exact:true}).click();
  await expect(page.getByTestId('station-label').filter({hasText:'PRE_01'})).toBeVisible();
  await page.screenshot({path:test.info().outputPath('gantt-small.png'),fullPage:true});
  await page.getByRole('button',{name:'Accept & Save',exact:true}).click();
  await page.getByRole('button',{name:'Accept & Save',exact:true}).last().click();
  await page.getByRole('button',{name:'Apply to Production'}).click();
  await expect(page.getByRole('heading',{name:'Production Execution'})).toBeVisible();
  await page.getByLabel('Status J001',{exact:true}).selectOption('Completed');
  await expect(page.locator('tbody tr').filter({hasText:'J001'}).getByText('Completed',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Analytics & Reports',exact:true}).click();
  await expect(page.getByText('1 / 10',{exact:true})).toBeVisible();

  if(await page.getByRole('button',{name:'Input Data',exact:true}).getAttribute('aria-expanded')==='false')await page.getByRole('button',{name:'Input Data',exact:true}).click();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Jobs',exact:true}).click();
  await page.getByLabel('Upload Input File').setInputFiles('tests/fixtures/TEST_AL13_50.json');
  await expect(page.getByText(/TEST_AL13_50.json/)).toBeVisible();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('MLPSO population',{exact:true}).fill('6');
  await page.getByLabel('MLPSO iterations',{exact:true}).fill('2');
  await page.getByRole('button',{name:'Save Changes'}).click();
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.getByRole('button',{name:'Create Schedule'}).click();
  await page.getByRole('checkbox',{name:'Select all filtered jobs'}).check();
  await page.getByRole('button',{name:'Validate Data'}).click();
  await expect(page.getByText('50 jobs · Large Scale')).toBeVisible();
  // The current complexity rule chooses one engine: 500 legacy operations select MLPSO.
  await expect(page.getByRole('radio',{name:'Automatic',exact:true})).toBeChecked();
  await expect(page.getByText('Runs: MLPSO',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Run Optimization'}).click();
  await expect(page.getByRole('heading',{name:'Scheduling Result'})).toBeVisible({timeout:90_000});
  await verifyAutomaticResult('MLPSO',500);
  await page.getByRole('button',{name:'Algorithm Comparison',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.locator('tbody tr').filter({hasText:'MLPSO'})).toContainText('Feasible');
  await page.screenshot({path:test.info().outputPath('comparison-large.png'),fullPage:true});
  await page.getByRole('button',{name:'Schedule Table',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(50);
  await expect(page.getByTestId('operation-table')).toContainText('500 / 500 operations');
  expect(browserErrors).toEqual([]);
});
