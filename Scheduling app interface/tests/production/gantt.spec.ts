import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const fixture=JSON.parse(readFileSync('.tmp-verification/reopen-fixture.json','utf8'));
test('Saved MILP Gantt: labels, colors, search, details, filters, zoom, sticky axis and shared table',async({page,request})=>{
  const optimization:string[]=[];
  page.on('request',r=>{if(r.method()==='POST'&&/\/schedules\/.*(run|rerun)/.test(r.url())) optimization.push(r.url());});
  await page.goto('/');
  await page.locator('input[type=password]').fill('planner-demo');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Production Dashboard'})).toBeVisible();
  const token=await page.evaluate(()=>sessionStorage.getItem('al13-token'));
  const headers={Authorization:'Bearer '+token};
  const result=await(await request.get('/api/schedules/'+fixture.small_id+'/result',{headers})).json();
  const ops=result.selected.operations;
  const calendar=await(await request.get('/api/calendar?dataset_id='+result.request.dataset_id,{headers})).json();
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await page.getByText(fixture.small_id,{exact:true}).click();
  await page.getByRole('button',{name:'Hourly view',exact:true}).click();
  const bars=page.getByTestId('gantt-bar');
  await expect(bars).toHaveCount(100);
  await expect(page.getByLabel('Color by',{exact:true})).toHaveValue('Job');
  await expect(page.getByLabel('Job color legend',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Status color legend',{exact:true})).toHaveCount(0);
  const identities=await bars.evaluateAll(nodes=>nodes.map(n=>[n.getAttribute('data-job'),n.getAttribute('data-operation'),n.getAttribute('data-start'),n.getAttribute('data-finish'),Number(n.getAttribute('data-processing'))]).sort());
  expect(identities).toEqual(ops.map((o:any)=>[o.jobId,o.operation,o.startTime,o.finishTime,o.processingMin]).sort());
  const colors=await bars.evaluateAll(nodes=>nodes.map(n=>({job:n.getAttribute('data-job'),color:(n as HTMLElement).style.backgroundColor})));
  for(const job of new Set(colors.map(c=>c.job))) expect(new Set(colors.filter(c=>c.job===job).map(c=>c.color)).size).toBe(1);
  await page.getByLabel('Search Job',{exact:true}).fill('J001');
  await expect(page.locator('[data-testid="gantt-bar"][data-highlighted="true"]')).toHaveCount(10);
  await expect(bars).toHaveCount(100);
  await expect(page.locator('[data-testid="gantt-bar"][data-job="J002"]').first()).toHaveCSS('opacity','0.18');
  await page.getByRole('button',{name:'Clear / Reset'}).click();
  await expect(page.locator('[data-testid="gantt-bar"][data-highlighted="true"]')).toHaveCount(100);
  const first=ops.find((o:any)=>o.jobId==='J001');
  const bar=page.locator('[data-testid="gantt-bar"][data-job="J001"][data-operation="'+first.operation+'"]');
  const window=calendar.find((w:any)=>w.station_id===first.workstation&&w.window_id===first.windowId);
  await expect(bar).toHaveAttribute('aria-label',new RegExp('Saved shift ID: '+window.shift_id));
  await bar.hover();
  await expect(page.getByRole('tooltip')).toContainText(first.startTime);
  await expect(page.getByRole('tooltip')).toContainText(first.finishTime);
  await expect(page.getByRole('tooltip')).toContainText(first.processingMin.toLocaleString(undefined,{maximumFractionDigits:2})+' min');
  await bar.click();
  await expect(page.getByLabel('Job Details',{exact:true})).toBeVisible();
  await expect(page.locator('[data-testid="gantt-bar"][data-highlighted="true"]')).toHaveCount(10);
  await expect(page.getByLabel('Job Details',{exact:true}).locator('ol li')).toHaveCount(10);
  await page.getByRole('button',{name:'View in Schedule Table',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(10);
  await expect(page.getByLabel('Table Job filter')).toHaveValue('J001');
  await page.getByLabel('Table Job filter').selectOption('All');
  await expect(page.locator('tbody tr')).toHaveCount(100);
  await page.getByRole('button',{name:'Gantt View',exact:true}).click();
  await page.getByRole('button',{name:'Hourly view',exact:true}).click();
  for(const [name,field] of [['Job','jobId'],['Workstation','workstation'],['Operation','operation']] as const){
    const value=first[field];
    await page.getByLabel(name+' filter',{exact:true}).selectOption(value);
    await expect(bars).toHaveCount(ops.filter((o:any)=>o[field]===value).length);
    await page.getByLabel(name+' filter',{exact:true}).selectOption('All');
  }
  await page.getByLabel('Shift filter',{exact:true}).selectOption(window.shift_id);
  await expect(bars).toHaveCount(ops.filter((o:any)=>calendar.some((w:any)=>w.station_id===o.workstation&&w.window_id===o.windowId&&w.shift_id===window.shift_id)).length);
  await page.getByLabel('Shift filter',{exact:true}).selectOption('All');
  await page.getByLabel('Color by',{exact:true}).selectOption('Operation');
  await expect(page.getByLabel('Operation color legend',{exact:true})).toBeVisible();
  const opColors=await bars.evaluateAll(nodes=>nodes.map(n=>({op:n.getAttribute('data-operation'),color:(n as HTMLElement).style.backgroundColor})));
  for(const op of new Set(opColors.map(c=>c.op))) expect(new Set(opColors.filter(c=>c.op===op).map(c=>c.color)).size).toBe(1);
  await page.getByLabel('Color by',{exact:true}).selectOption('Status');
  await expect(page.getByLabel('Status color legend',{exact:true})).toContainText('Completed');
  await page.getByLabel('Color by',{exact:true}).selectOption('Job');
  await page.getByRole('button',{name:'Zoom in',exact:true}).click();
  await expect(page.getByTestId('zoom-level')).toHaveText('200%');
  const scroller=page.getByTestId('gantt-scroll');
  const leftBefore=await page.getByTestId('station-label').first().evaluate(el=>el.getBoundingClientRect().left);
  await scroller.evaluate(el=>{el.scrollLeft=300;});
  await expect.poll(()=>scroller.evaluate(el=>el.scrollLeft)).toBe(300);
  const leftAfter=await page.getByTestId('station-label').first().evaluate(el=>el.getBoundingClientRect().left);
  expect(leftAfter).toBe(leftBefore);
  for(let i=0;i<3;i++)await page.getByRole('button',{name:'Zoom in',exact:true}).click();
  await expect(page.getByRole('button',{name:'Zoom in',exact:true})).toBeDisabled();
  await scroller.evaluate(el=>{el.scrollLeft=0;});
  await page.screenshot({path:'.tmp-verification/gantt-labels-zoomed.png',fullPage:true});
  const labels=await bars.evaluateAll(nodes=>nodes.map(n=>({label:n.textContent,width:n.clientWidth,scroll:n.scrollWidth})));
  expect(labels.some(n=>n.label?.includes(' · '))).toBeTruthy();
  expect(labels.every(n=>!n.label||n.scroll<=n.width)).toBeTruthy();
  await page.getByRole('button',{name:'Zoom out',exact:true}).click();
  await expect(page.getByTestId('zoom-level')).toHaveText('800%');
  await page.getByRole('button',{name:'Fit Schedule',exact:true}).click();
  await expect(page.getByTestId('zoom-level')).toHaveText('100%');
  expect(await scroller.evaluate(el=>el.scrollLeft)).toBe(0);
  expect(await scroller.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
  expect((await page.getByTestId('axis-tick').allTextContents()).every(t=>/^\d{2}:(00|30)$/.test(t))).toBeTruthy();
  await page.screenshot({path:'.tmp-verification/gantt-improved.png',fullPage:true});
  await page.getByRole('button',{name:'Algorithm Comparison',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Gantt View',exact:true}).click();
  await page.getByRole('button',{name:'Hourly view',exact:true}).click();
  await page.reload();
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await page.getByText(fixture.small_id,{exact:true}).click();
  await expect(bars).toHaveCount(100);
  expect(await bars.evaluateAll(nodes=>nodes.map(n=>({job:n.getAttribute('data-job'),color:(n as HTMLElement).style.backgroundColor})))).toEqual(colors);
  expect(optimization).toEqual([]);
  expect(await(await request.get('/api/schedules/'+fixture.small_id+'/result',{headers})).json()).toEqual(result);
});
