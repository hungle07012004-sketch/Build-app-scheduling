import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const fixture=JSON.parse(readFileSync('.tmp-verification/reopen-fixture.json','utf8'));
// Read-only replay of the user's saved result; no optimization is performed.
const saved=JSON.parse(readFileSync('.tmp-verification/large-gantt-result.json','utf8'));
const calendar=JSON.parse(readFileSync('.tmp-verification/large-gantt-calendar.json','utf8'));
const stamp=(s:string)=>new Date(s.replace(' ','T')).getTime();

for(const copies of [1,2]) test(`Large Gantt navigation and full calendar (${11290*copies} events)`,async({page})=>{
  const ops=copies===1?saved.selected.operations:[...saved.selected.operations,...saved.selected.operations.map((o:any)=>({...o,eventId:o.eventId+'-stress'}))];
  const replay={...saved,selected:{...saved.selected,operations:ops}};
  const original=JSON.stringify(ops), calls:string[]=[];
  page.on('request',r=>{if(r.method()==='POST'&&/schedules.*(run|rerun)/.test(r.url()))calls.push(r.url());});
  await page.route('**/api/schedules/'+fixture.small_id+'/result',r=>r.fulfill({json:replay}));
  await page.route('**/api/calendar?run_id=*',r=>r.fulfill({json:calendar}));
  await page.goto('/');await page.locator('input[type=password]').fill('planner-demo');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Production Dashboard'})).toBeVisible();
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await page.getByText(fixture.small_id,{exact:true}).click();
  const scroll=page.getByTestId('gantt-scroll'),bars=page.getByTestId('gantt-bar');
  await expect(page.getByTestId('operation-count')).toHaveText(`${ops.length} / ${ops.length} operations`);
  const earliest=ops.reduce((a:any,b:any)=>stamp(a.startTime)<stamp(b.startTime)?a:b);
  const first=page.locator(`[data-testid="gantt-bar"][data-job="${earliest.jobId}"][data-start="${earliest.startTime}"]`).first();
  await expect(first).toBeInViewport();
  const domain=Number(await scroll.getAttribute('data-domain-start'));
  expect(new Date(domain).getHours()).toBe(0);
  expect(Number(await scroll.getAttribute('data-domain-end'))-domain).toBe(24*3600000);
  await expect(page.getByRole('button',{name:'1 Day',exact:true})).toHaveAttribute('aria-pressed','true');
  expect(await bars.count()).toBeLessThan(500);
  const windowEnd=Number(await scroll.getAttribute('data-domain-end'));
  const displayedIds=await bars.evaluateAll(ns=>ns.flatMap(n=>JSON.parse(n.getAttribute('data-event-ids')!)));
  for(const o of ops.filter((o:any)=>stamp(o.startTime)<windowEnd&&stamp(o.finishTime)>domain))expect(displayedIds).toContain(o.eventId);
  await page.screenshot({path:`.tmp-verification/large-gantt-initial-${copies}.png`});
  // Choose a job whose first event is late in the schedule.
  const firstByJob=new Map<string,number>();
  for(const o of ops)for(const id of o.jobIds||[o.jobId])firstByJob.set(id,Math.min(firstByJob.get(id)??Infinity,stamp(o.startTime)));
  const late=[...firstByJob].sort((a,b)=>b[1]-a[1])[0][0];
  await page.getByLabel('Search Job',{exact:true}).fill(late);
  await expect(page.getByLabel('Gantt Date')).toHaveValue(new Date(firstByJob.get(late)!).toLocaleDateString('sv-SE'));
  const highlighted=page.locator('[data-testid="gantt-bar"][data-highlighted="true"]');
  await expect(highlighted.first()).toBeAttached();
  await page.getByLabel('Job filter',{exact:true}).selectOption(late);
  await page.getByLabel('Search Job',{exact:true}).fill('');
  const target=bars.first();await target.hover();
  await expect(page.getByRole('tooltip')).toContainText(late);
  await expect(page.getByRole('tooltip')).toContainText(await target.getAttribute('data-start') as string);
  const width=await target.evaluate(el=>parseFloat((el as HTMLElement).style.width));
  const labelLeft=await page.getByTestId('station-label').first().evaluate(el=>el.getBoundingClientRect().left);
  await page.getByRole('button',{name:'Zoom in',exact:true}).click();
  expect(await bars.first().evaluate(el=>parseFloat((el as HTMLElement).style.width))).toBeCloseTo(width*2,1);
  expect(await page.getByTestId('station-label').first().evaluate(el=>el.getBoundingClientRect().left)).toBe(labelLeft);
  await page.getByRole('button',{name:'Clear / Reset',exact:true}).click();
  await page.getByRole('button',{name:'Fit Schedule',exact:true}).click();
  await expect.poll(()=>scroll.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1);
  expect(Number(await scroll.getAttribute('data-domain-end'))).toBeGreaterThanOrEqual(stamp(saved.request.horizon_end));
  expect(Number(await scroll.getAttribute('data-domain-start'))).toBeLessThanOrEqual(stamp(saved.request.horizon_start));
  expect(await bars.evaluateAll(ns=>ns.reduce((n,el)=>n+Number(el.getAttribute('data-event-count')),0))).toBe(ops.length);
  expect((await page.getByTestId('axis-tick').allTextContents()).some(s=>/Oct|Nov/.test(s))).toBe(true);
  await page.screenshot({path:`.tmp-verification/large-gantt-fit-${copies}.png`});
  await page.getByRole('button',{name:'Hourly view',exact:true}).click();
  await expect(first).toBeInViewport();
  expect(JSON.stringify(ops)).toBe(original);expect(calls).toEqual([]);
});
